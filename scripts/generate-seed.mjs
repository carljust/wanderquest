import { readFileSync, writeFileSync } from "node:fs";
const quest = JSON.parse(readFileSync("content/externsteine.v1.json", "utf8"));
const solutions = JSON.parse(
  readFileSync("content/solutions.private.json", "utf8"),
);
const quote = (value) =>
  value === null || value === undefined
    ? "null"
    : "'" + String(value).replaceAll("'", "''") + "'";
const json = (value) => quote(JSON.stringify(value)) + "::jsonb";
const published = structuredClone(quest);
for (const station of published.stations) {
  station.success = "";
  station.puzzle.hints = station.puzzle.hints.map(
    () => "Dieser Hinweis wird nach Anforderung vom Server geladen.",
  );
}
const rows = [
  "-- Generated by npm run seed:generate. Draft, NOT released for field play.",
  "begin;",
  `insert into public.quests(id,slug) values(${quote(quest.id)},'externsteine') on conflict do nothing;`,
  `insert into public.quest_versions(id,quest_id,revision,status,approval,field_ready,document) values(${quote(quest.versionId)},${quote(quest.id)},1,'draft','pending_source_review',false,${json(published)}) on conflict(id) do update set document=excluded.document where quest_versions.status='draft';`,
  `do $$ begin if not exists(select 1 from public.quest_versions where id=${quote(quest.versionId)} and status='draft') then raise exception 'Published versions are immutable; create a new version.'; end if; end $$;`,
];
for (const s of published.stations) {
  const original = quest.stations.find((item) => item.id === s.id);
  rows.push(
    `insert into public.stations(id,version_id,ordinal,title,latitude,longitude,radius_m,coordinate_status,seal,content) values(${[quote(s.id), quote(quest.versionId), s.order, quote(s.title), "null", "null", s.radius, quote(s.coordinateStatus), quote(s.seal), json(s)].join(",")}) on conflict(id) do update set content=excluded.content,title=excluded.title;`,
  );
  rows.push(
    `insert into public.puzzles(station_id,kind,prompt,options,hints,transcript) values(${[quote(s.id), quote(s.puzzle.kind), quote(s.puzzle.prompt), json(s.puzzle.options ?? []), json(s.puzzle.hints), quote(s.puzzle.transcript)].join(",")}) on conflict(station_id) do update set kind=excluded.kind,prompt=excluded.prompt,options=excluded.options,hints=excluded.hints,transcript=excluded.transcript;`,
  );
  rows.push(
    `insert into private.station_feedback(station_id,success,hints) values(${quote(s.id)},${quote(original.success)},${json(original.puzzle.hints)}) on conflict(station_id) do update set success=excluded.success,hints=excluded.hints;`,
  );
  rows.push(
    `insert into private.solutions(station_id,accepted) values(${quote(s.id)},array[${solutions[s.id].map(quote).join(",")}]) on conflict(station_id) do update set accepted=excluded.accepted;`,
  );
  s.dialogues.forEach((d, i) =>
    rows.push(
      `insert into public.dialogues(id,station_id,event,ordinal,speaker,text,mood) values(${[quote(s.id + "-" + i), quote(s.id), "'arrival'", i, quote(d.speaker), quote(d.text), quote(d.mood)].join(",")}) on conflict(id) do update set text=excluded.text,mood=excluded.mood;`,
    ),
  );
}
for (const a of quest.assets)
  rows.push(
    `insert into public.quest_assets(id,version_id,kind,description) values(${[quote(a.id), quote(quest.versionId), quote(a.kind), quote(a.description)].join(",")}) on conflict(version_id,id) do update set description=excluded.description;`,
  );
rows.push("commit;");
writeFileSync("supabase/seed.sql", rows.join("\n") + "\n");
